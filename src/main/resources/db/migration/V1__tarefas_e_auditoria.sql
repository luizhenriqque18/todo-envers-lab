CREATE SEQUENCE revisao_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE revisao (
    id INTEGER PRIMARY KEY,
    instante BIGINT NOT NULL,
    autor VARCHAR(100) NOT NULL
);

CREATE TABLE tarefa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(2000),
    concluida BOOLEAN NOT NULL,
    criada_em TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE tarefa_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL REFERENCES revisao(id),
    revtype SMALLINT,
    titulo VARCHAR(150),
    descricao VARCHAR(2000),
    concluida BOOLEAN,
    criada_em TIMESTAMP(6) WITH TIME ZONE,
    titulo_mod BOOLEAN,
    descricao_mod BOOLEAN,
    concluida_mod BOOLEAN,
    criada_em_mod BOOLEAN,
    PRIMARY KEY (id, rev)
);
CREATE INDEX idx_tarefa_aud_rev ON tarefa_aud(rev);
